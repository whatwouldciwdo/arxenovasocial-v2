import { createHash } from 'node:crypto';
import { cp, mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium } from '@playwright/test';

const project = fileURLToPath(new URL('../', import.meta.url));

export async function generateHomeTree(home) {
  // Keep this render-time transformation identical to data/html-home.ts.
  const normalized = home
    .replace(/src="public\//g, 'src="/').replace(/src=\\"public\//g, 'src=\\"/');
  const boundary = '</div></div></div></div></div></div></div></section><section id="process"';
  if (normalized.split(boundary).length !== 2) throw new Error('Unexpected Problems/Process boundary');
  const source = normalized.replace(boundary, '</div></div></div></section><section id="process"');
  const sourceSha256 = createHash('sha256').update(source, 'utf8').digest('hex');
  const browser = await chromium.launch();
  let tree;
  try {
    const page = await browser.newPage({ offline: true });
    tree = await page.evaluate((html) => {
      // Match the real Home div's fragment parsing. Wrapping a complete document
      // string lets legacy unmatched closing tags terminate the synthetic root early.
      const root = document.createElement('div');
      root.innerHTML = html;
      if (root.querySelectorAll('#process').length !== 1) throw new Error('Expected one Process section');
      function visit(node) {
        if (node.nodeType === Node.TEXT_NODE) return node.textContent;
        if (!(node instanceof Element)) throw new Error(`Unsupported shell node ${node.nodeType}`);
        if (node.id === 'process') return { candidate: true };
        const props = Object.fromEntries(Array.from(node.attributes, ({ name, value }) => {
          if (name === 'style') throw new Error('Shell inline style needs an explicit React mapping');
          return [name === 'class' ? 'className' : name === 'tabindex' ? 'tabIndex' : name, value];
        }));
        const branch = !!node.querySelector('#process');
        return { tag: node.localName, props: node === root ? {} : props,
          ...(branch ? { children: Array.from(node.childNodes, visit) } : { html: node.innerHTML }) };
      }
      return visit(root);
    }, source);
  } finally {
    await browser.close();
  }
  return '// Generated by node scripts/generate-home-tree.mjs; do not edit.\n'
    + `export const HOME_TREE_SOURCE_SHA256 = '${sourceSha256}';\n`
    + `export default ${JSON.stringify(tree)};\n`;
}

// Importing the generation helper must not prepare or overwrite the fixture.
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  // The disposable fixture uses the promoted page, loader, layout and runtime as-is.
  // PROCESS_USE_LEGACY=1 selects its fallback, exactly as in production.
  const target = path.join(project, 'artifacts/project-process/integration-app');
  const tree = await generateHomeTree(await readFile(path.join(project, 'data/home.html'), 'utf8'));
  await mkdir(target, { recursive: true });
  for (const entry of ['app', 'components/home', 'data', 'public', 'tsconfig.json', 'next-env.d.ts', 'next.config.mjs', 'package.json']) {
    await cp(path.join(project, entry), path.join(target, entry), { recursive: true });
  }
  await writeFile(path.join(target, 'data/process-integration-tree.ts'), tree);
  await writeFile(path.join(target, '.gitignore'), '.next/\n');
  console.log(`Prepared isolated Next fixture: ${target}`);
}
